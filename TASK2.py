import math

num = int(input("Enter a number: "))

square_root_number = math.sqrt(num)
natural_logarithm = math.log(num)
sine_value_number = math.sin(num)

print("Square root of the number:", square_root_number)
print("Natural logarithm of the number:", natural_logarithm)
print("Sine of the number (in radians):", sine_value_number)
